//! Deterministic reports and local SVG badges; no network or badge service is involved.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use rust_forth_vm::Cell;

use super::model::{percentage, Outcome, Status};

/// The reviewed native configuration used by the checked-in README artifacts.
pub fn canonical() -> bool {
    cfg!(all(target_pointer_width = "64", target_endian = "little"))
}

/// Makes table contents safe without changing their visible meaning.
fn table(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('|', "\\|")
        .replace('\n', " ")
}

/// Renders a source-attributed requirement report from measured results.
pub fn markdown(
    outcomes: &[Outcome],
    words: &std::collections::BTreeSet<String>,
    revision: &str,
) -> String {
    let mut text = format!("# Forth conformance report\n\nGenerated by `make conformance`. Do not edit this report or its badges by hand.\n\nMeasured source revision: `{revision}` (content fingerprint, not a Git commit).\n\nConfiguration: {}-bit {}-endian native `usize` cells; default VM stacks; 8192-cell test dictionary.\n\n", Cell::BITS, if cfg!(target_endian = "little") { "little" } else { "big" });
    text.push_str("The score is **100 × passed mandatory register units / all mandatory register units**. Each word definition and each registered general clause counts once, regardless of the number of probes. Missing, deviating, blocked, and unassessed units remain in the denominator. A pass means all assigned probes passed, not that every aspect of a clause has been proved. This is sampled evidence, not certification.\n\nThe [guide](../conformance.md) documents scope, source provenance, optional word sets, and limitations. The [requirements register](../../tests/conformance/requirements.tsv) gives stable IDs and references. Check IDs refer to [public-API probes](../../tests/conformance/cases.rs); `host.*` checks inspect the public Cell type or word inventory. Dependencies list missing words or test facilities.\n\nISO links below point to the supporting **DPANS94 draft**, not the normative ISO publication. They preserve the corresponding clause numbering and do not substitute Forth 2012 text.\n\n");
    for (profile, title) in [("f83", "FORTH-83"), ("iso", "ISO Forth")] {
        text.push_str(&format!("## {title}\n\n"));
        let selected: Vec<_> = outcomes
            .iter()
            .filter(|o| o.requirement.profile == profile)
            .collect();
        let passed = selected
            .iter()
            .filter(|o| o.status == Status::Passed)
            .count();
        let percent = percentage(passed, selected.len()).expect("nonempty validated profile");
        let word_count = selected
            .iter()
            .filter(|o| o.requirement.kind == "word")
            .count();
        let present = selected
            .iter()
            .filter(|o| o.requirement.kind == "word" && words.contains(&o.requirement.subject))
            .count();
        text.push_str(&format!("**{percent} — {passed}/{} mandatory register units passed.** Word availability: {present}/{word_count}; presence alone does not earn a pass.\n\n", selected.len()));
        text.push_str("| Category | Passed | Deviating | Missing | Blocked | Not yet assessed | Total |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |\n");
        for kind in ["word", "system"] {
            let rows: Vec<_> = selected
                .iter()
                .filter(|o| o.requirement.kind == kind)
                .collect();
            text.push_str(&format!("| {kind} |"));
            for status in [
                Status::Passed,
                Status::Deviating,
                Status::Missing,
                Status::Blocked,
                Status::Unassessed,
            ] {
                text.push_str(&format!(
                    " {} |",
                    rows.iter().filter(|o| o.status == status).count()
                ));
            }
            text.push_str(&format!(" {} |\n", rows.len()));
        }
        text.push_str("\n| ID | Kind / subject | Provision | Status | Checks / failed checks | Missing prerequisites | Evidence or reason |\n| --- | --- | --- | --- | --- | --- | --- |\n");
        for outcome in selected {
            let r = &outcome.requirement;
            text.push_str(&format!(
                "| `{}` | {} / `{}` | [{}]({}) | {} | {} / {} | {} | {} |\n",
                r.id,
                r.kind,
                r.subject.replace('|', "\\|"),
                table(&r.provision),
                r.source,
                outcome.status.name(),
                table(&outcome.checks.join(", ")),
                table(&outcome.failed.join(", ")),
                table(&outcome.dependencies.join(", ")),
                table(&outcome.reason)
            ));
        }
        text.push('\n');
    }
    text.truncate(text.trim_end().len());
    text.push('\n');
    text
}

/// An accessible, static SVG with fixed geometry and no external resources.
pub fn badge(label: &str, percent: &str) -> String {
    let color = if percent == "100.0%" {
        "#22863a"
    } else {
        "#9a6700"
    };
    format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" width="245" height="20" role="img" aria-label="{label}: {percent}">
  <title>{label}: {percent}</title>
  <rect width="245" height="20" rx="3" fill="#555"/>
  <path d="M177 0h65a3 3 0 0 1 3 3v14a3 3 0 0 1-3 3h-65z" fill="{color}"/>
  <g fill="#fff" text-anchor="middle" font-family="Verdana,Geneva,sans-serif" font-size="11">
    <text x="88.5" y="14">{label}</text>
    <text x="211" y="14">{percent}</text>
  </g>
</svg>
"##
    )
}

/// Generates every artifact from the same measured results.
pub fn artifacts(
    outcomes: &[Outcome],
    words: &std::collections::BTreeSet<String>,
    revision: &str,
) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    files.insert(
        "docs/conformance/report.md".into(),
        markdown(outcomes, words, revision),
    );
    for (profile, label) in [
        ("f83", "FORTH-83 conformance"),
        ("iso", "ISO Forth conformance"),
    ] {
        let rows: Vec<_> = outcomes
            .iter()
            .filter(|o| o.requirement.profile == profile)
            .collect();
        let score = percentage(
            rows.iter().filter(|o| o.status == Status::Passed).count(),
            rows.len(),
        )
        .expect("nonempty profile");
        files.insert(
            format!("docs/conformance/{profile}.svg"),
            badge(label, &score),
        );
    }
    files
}

/// Lists every file contributing to the measurement; generated artifacts are excluded.
fn source_paths(root: &Path) -> Vec<PathBuf> {
    fn walk(root: &Path, directory: &Path, paths: &mut Vec<PathBuf>) {
        for entry in fs::read_dir(root.join(directory)).unwrap() {
            let relative = directory.join(entry.unwrap().file_name());
            if root.join(&relative).is_dir() {
                walk(root, &relative, paths);
            } else {
                paths.push(relative);
            }
        }
    }
    let mut paths = Vec::new();
    for directory in ["src", "tests/conformance"] {
        walk(root, Path::new(directory), &mut paths);
    }
    paths.extend(
        [
            "Cargo.toml",
            "Cargo.lock",
            "tests/conformance.rs",
            "Makefile",
            "README.md",
            "docs/conformance.md",
            "docs/words.md",
        ]
        .map(PathBuf::from),
    );
    paths.sort();
    paths
}

/// FNV-1a identifies the input content without a self-referential Git commit or timestamps.
/// This is a reproducibility identifier, not a cryptographic integrity claim.
pub fn source_revision(root: &Path) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for path in source_paths(root) {
        let name = path.to_str().unwrap().as_bytes();
        let bytes = fs::read(root.join(&path)).unwrap();
        for byte in name
            .iter()
            .chain([0_u8].iter())
            .chain(bytes.iter())
            .chain([0_u8].iter())
        {
            hash ^= u64::from(*byte);
            hash = hash.wrapping_mul(0x100_0000_01b3);
        }
    }
    format!("fnv1a64:{hash:016x}")
}

/// Fails on a missing or stale generated file; checks never rewrite repository files.
pub fn check_files(root: &Path, files: &BTreeMap<String, String>) -> Result<(), String> {
    let stale: Vec<_> = files
        .iter()
        .filter(|(path, expected)| {
            fs::read_to_string(root.join(path)).ok().as_ref() != Some(expected)
        })
        .map(|(path, _)| path.as_str())
        .collect();
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "stale conformance artifacts: {stale:?}; run make conformance"
        ))
    }
}
